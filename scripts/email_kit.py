#!/usr/bin/env python3
"""Builds worker/slate-kit.js: the slate's own rules, copied from the app, for the morning email.

The email has to look like the slate page, so the server uses the app's exact code for the card's corner tag
("Heavyweights", "All NBA", "Your team") and the one-line preview under each game ("Celtics have won five in a row").
This copies those functions word for word out of src/app/ into one module, so the two never drift apart.

    python3 scripts/email_kit.py          rewrite worker/slate-kit.js
    python3 scripts/email_kit.py --check  exit 1 if it's out of date (run after changing the slate engine or preview lines)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "worker", "slate-kit.js")
TAKE = {
    "010-core.js": ["LEAGUES", "ORDER", "clone", "NATIONAL_TV"],
    "050-slate-engine.js": ["RULE_DEFAULTS", "EVENT_RX", "isEvent", "eventKey", "CONF_RX", "EV_SPORT", "evSport", "evGroup", "evGroupOn", "evNameOn",
                            "eventOn", "SOCCER", "LG_OPTS", "CHOICES", "BIG_CLUBS", "ENGLISH", "BIG_NATIONS", "inList", "isUSA", "isKnockout",
                            "isCompetitive", "TOP_N", "NAT_EXTRA", "BIG_SIX", "NFL_DIV", "normLg", "normRules", "natFor", "winRec", "standNo",
                            "bigSix", "topLabel", "MATCH", "lgRules", "ruleHits"],
    "040-live.js": ["ESPN_URLS", "abbr", "short", "sideOrder", "sep"],
    "060-cards.js": ["SPORT", "SPORT_PATH"],
    "090-box-data.js": ["BX_SPORT"],
    "110-box-score.js": ["bxBase", "bxSummaryUrl", "bxApi"],
    "100-highlights.js": ["pvCompute", "pvBlandHead", "pvAllHome", "QBD", "depthOf", "pvQB"],
    "080-claude.js": ["l5Season", "recapStandouts", "clDay", "trimEspn", "clGame"],
}

def grab(lines, name, fn):
    rx = re.compile(r"^  (var %s\b|function %s\()" % (re.escape(name), re.escape(name)))
    for i, l in enumerate(lines):
        if rx.match(l):
            out, j = [l], i
            closes = lambda s: s.rstrip().endswith(";") or (s.startswith("  function") and s.rstrip().endswith("}"))
            if closes(l) and l.count("{") == l.count("}") and l.count("[") == l.count("]"):
                pass
            else:
                while True:
                    j += 1; out.append(lines[j])
                    if re.match(r"^  (\}|\]|\});?\s*$", lines[j]): break
            if name == "NFL_DIV":  # its teams are filled in by the two lines after it
                while not lines[j].rstrip().endswith("});"): j += 1; out.append(lines[j])
            return out
    sys.exit("email_kit.py: couldn't find %s in src/app/%s" % (name, fn))

def build():
    parts = []
    for fn, names in TAKE.items():
        lines = open(os.path.join(ROOT, "src", "app", fn), encoding="utf-8").read().split("\n")
        parts.append("  // ---- from src/app/%s" % fn)
        for n in names: parts += grab(lines, n, fn)
    body = "\n".join(parts)
    return HEAD + body + TAIL

HEAD = '''// GENERATED by scripts/email_kit.py from src/app/ (the app's own code, word for word). Don't edit: run the script.
// The morning email (worker/morning-email.js) uses it so its cards say what the slate says: the corner tag and the
// one-line preview under each game.
/* eslint-disable */
export function slateKit(opts) {
  // what the copied code expects from the app around it
  var state = { rules: opts.rules || null };
  var HOME_TZ = "America/Chicago";
  var mine = opts.mine || {};
  function hasFav(g) { return !!mine[g.id]; }
  function info(g) { var L = LEAGUES[g.league] || {}; return { tag: L.tag || String(g.league || "").toUpperCase().slice(0, 5), name: L.name || "Other" }; }
  function hourCT(iso) { var h = Number(new Intl.DateTimeFormat("en-US", { timeZone: HOME_TZ, hour: "numeric", hourCycle: "h23" }).format(new Date(iso))); return h < 4 ? h + 24 : h; }
  function quickRecap() { return null; }  // the app's own box-score recap needs its loaded box scores; Claude doesn't need it
  function rkFetch(u) { return fetch(u, { headers: { "user-agent": "slate-email" } }).then(function (r) { return r.ok ? r.json() : null; }, function () { return null; }); }
'''
TAIL = '''
  state.rules = normRules(state.rules || RULE_DEFAULTS);
  return { ruleHits: ruleHits, pvCompute: pvCompute, pvQB: pvQB, trimEspn: trimEspn, clGame: clGame, short: short, sideOrder: sideOrder, sep: sep, SPORT: SPORT, SPORT_PATH: SPORT_PATH, hourCT: hourCT, rkFetch: rkFetch, bxSummaryUrl: bxSummaryUrl, info: info, abbr: abbr, BX_SPORT: BX_SPORT, LEAGUES: LEAGUES };
}
'''

if __name__ == "__main__":
    js = build()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != js: sys.exit("worker/slate-kit.js is out of date: run python3 scripts/email_kit.py")
        print("worker/slate-kit.js is current"); sys.exit(0)
    open(OUT, "w", encoding="utf-8").write(js)
    print("wrote worker/slate-kit.js (%d KB)" % (len(js) // 1024))
